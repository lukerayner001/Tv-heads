import { createRequire } from 'module'; const { chromium } = createRequire(import.meta.url)(process.env.PWPATH);
const b = await chromium.launch({ args: ['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--disable-features=WebRtcHideLocalIpsWithMdns','--use-gl=swiftshader','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required'] });
const url = 'http://127.0.0.1:8080/tv-heads.html?peerhost=127.0.0.1&peerport=9000';
const errs = [];
const mk = async (n) => { const c = await b.newContext(); const p = await c.newPage(); p.on('pageerror', e => errs.push(n+': '+e.message)); await p.goto(url); return p; };
const A = await mk('A'), B = await mk('B');
await A.fill('#name','Luke'); await A.click('#hostBtn');
await A.waitForFunction(() => document.getElementById('roomcode').textContent.length===4);
const code = await A.textContent('#roomcode');
await B.fill('#name','Bodhi'); await B.fill('#code', code); await B.click('#joinBtn');
await A.waitForFunction(() => [...window.__tv.remotes.values()].some(p => p.voice && p.seen), null, {timeout:20000});
const probe = (pg) => pg.evaluate(() => { const p=[...window.__tv.remotes.values()][0]; return { ctx: window.__tv.audioCtx.state, vol: +(p.vol??-1).toFixed(2), gain: +p.voice.gain.gain.value.toFixed(2), pan: +p.voice.pan.pan.value.toFixed(2), talking: p.talking, label: p.name, muted: !!p.muted }; });
await A.evaluate(() => { const m=window.__tv.me; m.pos.set(0,0,-10); m.rot=Math.PI; });
await B.evaluate(() => { const m=window.__tv.me; m.pos.set(-3,0,-12); m.rot=0; });
await A.waitForTimeout(1500); console.log('near', await probe(A));
await B.evaluate(() => { window.__tv.me.pos.set(0,0,20); });
await A.waitForTimeout(1500); console.log('far', await probe(A));
await B.evaluate(() => { window.__tv.me.pos.set(0,0,-18); });
await B.keyboard.press('KeyM');
await A.waitForTimeout(1500); console.log('mid + B muted', await probe(A));
console.log('errors', errs); await b.close();
